/**
 * 整份物化的分页参数：**服务端与界面共用同一份**，别在两处各写一个数。
 *
 * 为什么单独一个文件：界面（客户端组件）要用它渲染"每页读多少行"，
 * 而物化的实现在 `object-service` 里、牵着数据源连接器 —— 客户端**不能** import 那个模块。
 *
 * 口径：读一页写一页之后，内存只跟页大小成正比，所以页可以开得比过去（500）大得多；
 * 但页越大，单次查询在业务库那侧越重，所以给出上限与默认值两个边界。
 */
export const DEFAULT_MATERIALIZE_PAGE_SIZE = 2000;
/**
 * 页大小上限 = **数据源连接器单次读取的硬上限**（见 `@/lib/datasource/sql` 的 `VIEW_LIMIT_MAX`，
 * 现在是 5000）。要更多也只会拿到 5000，所以上限就定在这里 —— 否则物化会拿"我请求了 20000"
 * 去判断"这一页读满了没有"，把连接器的上限误判成"源读完了"（实测踩过）。
 */
export const MAX_MATERIALIZE_PAGE_SIZE = 5000;
export const MIN_MATERIALIZE_PAGE_SIZE = 200;
